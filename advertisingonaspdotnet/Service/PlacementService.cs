
using advertisingonaspdotnet.Domain;
using advertisingonaspdotnet.Persistence;
using advertisingonaspdotnet.Contracts;
using advertisingonaspdotnet.Telemetry;

namespace advertisingonaspdotnet.Service;

public interface IPlacementService {

    Task Create(Placement model , CancellationToken cancellationToken);
    Task<bool> Update(Placement model, CancellationToken cancellationToken);
    Task<Placement?> Get(IdentifierRequest identifier, CancellationToken cancellationToken);
    Task<IReadOnlyList<Placement>> GetAll(CancellationToken cancellationToken);
    Task<bool> Delete(IdentifierRequest identifier, CancellationToken cancellationToken);
    // ------------------------------
    // Single Associations
    // -------------------------------
    Task<bool> AssignLineItem(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> UnassignLineItem(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> AssignAdSlot(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> UnassignAdSlot(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> AssignDeal(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> UnassignDeal(AssociationRequest request, CancellationToken cancellationToken);


}

public class PlacementService : IPlacementService
{
    private readonly ApplicationTelemetry _telemetry;
    private readonly IPlacementRepository _repository;
    private readonly ILogger<PlacementService> _logger;
    private readonly IServiceResolver _serviceResolver;


    public PlacementService(
        ApplicationTelemetry telemetry,
        IPlacementRepository repository,
        ILogger<PlacementService> logger,
        IServiceResolver serviceResolver)
    {
        _telemetry = telemetry;
        _repository = repository;
        _logger = logger;
        _serviceResolver = serviceResolver;
    }

    public async Task Create(Placement model, CancellationToken cancellationToken)
    {
        try
        {
            await _telemetry.Execute(
                "Placement",
                "CreatePlacement",
                () => _repository.AddAsync(model, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
        }
    }

    public async Task<bool> Update(Placement model, CancellationToken cancellationToken)
    {
        try {
            var existing = await _repository.GetByIdAsync(model.Id, cancellationToken);
            if (existing is null)
            {
                return false;
            }
            existing.Name = model.Name;
            existing.Flight = model.Flight;
            existing.GoalImpressions = model.GoalImpressions;

            await _telemetry.Execute(
                "Placement",
                "UpdatePlacement",
                () => _repository.UpdateAsync(existing, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public Task<Placement?> Get(IdentifierRequest identifier, CancellationToken cancellationToken)
    => _repository.GetByIdAsync(identifier.Id, cancellationToken);

    public Task<IReadOnlyList<Placement>> GetAll(CancellationToken cancellationToken)
    => _repository.GetAllAsync(cancellationToken);

    public async Task<bool> Delete(IdentifierRequest identifier, CancellationToken cancellationToken)
    {
        var existing = await _repository.GetByIdAsync(identifier.Id, cancellationToken);
        if (existing is null)
        {
            return false;
        }

        try
        {
            await _telemetry.Execute(
                "Placement",
                "UpdatePlacement",
                () => _repository.DeleteAsync(existing, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public async Task<bool> AssignLineItem(AssociationRequest request, CancellationToken cancellationToken) {

        var parent = await _repository.GetByIdAsync(request.ParentId, cancellationToken);
        if (parent is null)
        {
            _logger.LogError("No Placement found using Id {ParentId}", request.ParentId);
            return false;
        }

        try
        {
            var childRequest = new IdentifierRequest
            {
                Id = request.ChildId,
            };

            var child = await _serviceResolver.Get<LineItemService>().Get(childRequest, cancellationToken);
            parent.LineItem = child;
            await Update( parent, cancellationToken );
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public async Task<bool> UnassignLineItem(AssociationRequest request, CancellationToken cancellationToken) {
        var parent = await _repository.GetByIdAsync(request.ParentId, cancellationToken);
        if (parent is null)
        {
            _logger.LogError("No Placement found using Id {ParentId}", request.ParentId);
            return false;
        }

        try
        {
            parent.LineItem = null;
            await Update( parent, cancellationToken );
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

